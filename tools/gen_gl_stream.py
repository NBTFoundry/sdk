"""Generate the OpenGL ES 2.0 command stream of Mode B guests.

A guest has no GL of its own: its gl* calls append commands to the arena it
shares with the runner (include/nbt/gl_stream.h, which has the wire format),
and the runner executes them on its context. From Khronos' gl.xml this writes:

  gl_commands.h   (both)    the command ids: GLES 2.0 sorted by name, from 1
  gl_encode.c     (guest)   one encoder per command, the table for gl_proc
  gl_decode.c     (runner)  one decoder per command: checks, then the call
  gl_functions.h  (runner)  the table of the driver's entry points

Commands whose sizes depend on GL state are hand-written on both sides
(guest/gl_stream.c, runner/gl_runner.c) and only declared here.

Usage: gen_gl_stream.py <gl.xml> <output directory>
"""
import os
import re
import sys

from glregistry import gles2_commands

# Hand-written on both sides (state-dependent sizes, client arrays, strings).
SPECIAL = {
    "glVertexAttribPointer", "glDrawArrays", "glDrawElements", "glGetBooleanv", "glGetIntegerv",
    "glGetFloatv", "glReadPixels", "glTexImage2D", "glTexSubImage2D", "glShaderSource", "glGetString",
    "glGetVertexAttribPointerv", "glGetUniformfv", "glGetUniformiv",
}
# Of those, answered in the guest and never sent: the runner has no decoder.
GUEST_ONLY = {"glGetVertexAttribPointerv", "glGetUniformfv", "glGetUniformiv"}
# State the hand-written commands need: the guest records it before encoding
# (nbtgl_track_*), the runner after executing.
GUEST_TRACKED = {"glBindBuffer", "glDeleteBuffers", "glPixelStorei", "glEnableVertexAttribArray",
                 "glDisableVertexAttribArray"}
RUNNER_TRACKED = {"glEnableVertexAttribArray", "glDisableVertexAttribArray"}
# COMPSIZE(pname) parameters that are always one value in OpenGL ES 2.0.
ONE_VALUE = {"glGetBufferParameteriv", "glGetFramebufferAttachmentParameteriv", "glGetProgramiv",
             "glGetRenderbufferParameteriv", "glGetShaderiv", "glGetTexParameterfv", "glGetTexParameteriv",
             "glTexParameterfv", "glTexParameteriv"}
# Outputs gl.xml sizes for their largest query: four values for this pname,
# one for every other. Copying four back into a caller's single value would
# write past it.
FOUR_IF = {"glGetVertexAttribfv": "GL_CURRENT_VERTEX_ATTRIB", "glGetVertexAttribiv": "GL_CURRENT_VERTEX_ATTRIB"}

ELEM = {"GLboolean": 1, "GLchar": 1, "GLubyte": 1, "GLbyte": 1, "void": 1, "GLshort": 2, "GLushort": 2}
FLOATS = {"GLfloat", "GLclampf"}
BANNER = "/* Generated by tools/gen_gl_stream.py from Khronos gl.xml: OpenGL ES 2.0. */"


def ident(cmd):
    return "NBTGL_ID_" + cmd.name


def length_expr(cmd, p):
    """Bytes of a pointer parameter as C (64-bit, so a hostile or negative
    count cannot wrap), or None when it needs a hand."""
    if p.pointer and p.const and p.base == "GLchar" and not p.len:
        return "STRING"  # a name: its length travels with it
    if p.len is None:
        return None
    elem = ELEM.get(p.base, 4)
    if p.len.startswith("COMPSIZE"):
        return "%d" % elem if cmd.name in ONE_VALUE else None
    if cmd.name in FOUR_IF and p.pointer and not p.const:
        return "((uint64_t)((pname) == %s ? 4 : 1) * %d)" % (FOUR_IF[cmd.name], elem)
    expr = re.sub(r"[A-Za-z_]\w*", lambda m: "(uint64_t)(uint32_t)(%s)" % m.group(0), p.len)
    return "((%s) * %d)" % (expr, elem)


class Shape:
    """How a command travels: its scalars, input and output pointers."""

    def __init__(self, cmd):
        params = cmd.params
        self.scalars = [p for p in params if not p.pointer]
        self.ins = [p for p in params if p.pointer and p.const]
        self.outs = [p for p in params if p.pointer and not p.const]
        self.size = {p.name: length_expr(cmd, p) for p in self.ins + self.outs}
        unknown = [n for n, v in self.size.items() if v is None]
        if unknown:
            sys.exit("%s: %s has no known size; add the command to SPECIAL" % (cmd.name, unknown[0]))
        self.sync = cmd.ret != "void" or bool(self.outs)

    def bytes_of(self, p):
        s = self.size[p.name]
        return "(strlen(%s) + 1)" % p.name if s == "STRING" else s


def encoder(cmd, s):
    fail = "" if cmd.ret == "void" else " 0"
    b = []
    if cmd.name in GUEST_TRACKED:
        b.append("  nbtgl_track_%s(%s);" % (cmd.name, cmd.args()))
    b.append("  const uint64_t nbt_bytes = %d * 4%s;" % (
        1 + len(s.scalars) + len(s.outs), "".join(" + 4 + NBTGL_PAD(%s)" % s.bytes_of(p) for p in s.ins)))
    b.append("  uint32_t* nbt_w = nbtgl_begin(%s, nbt_bytes);" % ident(cmd))
    b.append("  if (!nbt_w) return%s;" % fail)
    for i, p in enumerate(s.scalars, start=1):
        if p.base in FLOATS:
            b.append("  memcpy(&nbt_w[%d], &%s, 4);" % (i, p.name))
        else:
            b.append("  nbt_w[%d] = (uint32_t)%s;" % (i, p.name))
    b.append("  size_t nbt_at = %d;" % (1 + len(s.scalars)))
    for p in s.ins:
        b.append("  nbt_at = nbtgl_put(nbt_w, nbt_at, %s, (size_t)%s);" % (p.name, s.bytes_of(p)))
    for p in s.outs:
        b.append("  nbt_w[nbt_at++] = (uint32_t)%s;" % s.bytes_of(p))
    b.append("  nbtgl_end(nbt_w, nbt_at);")
    if s.sync:
        b.append("  const uint8_t* nbt_r = nbtgl_sync();")
        if s.outs:
            b.append("  size_t nbt_off = 4;")
        for p in s.outs:
            b.append("  if (nbt_r && %s) memcpy(%s, nbt_r + nbt_off, (size_t)%s);" % (p.name, p.name, s.bytes_of(p)))
            b.append("  nbt_off += NBTGL_PAD(%s);" % s.bytes_of(p))
        if s.outs:
            b.append("  (void)nbt_off;")
        if cmd.ret != "void":
            b.append("  %s nbt_v = 0;" % cmd.ret)
            b.append("  if (nbt_r) memcpy(&nbt_v, nbt_r, sizeof(nbt_v) < 4 ? sizeof(nbt_v) : 4);")
            b.append("  return nbt_v;")
    return "static %s enc_%s(%s) {\n%s\n}" % (cmd.ret, cmd.name, cmd.decl(), "\n".join(b))


def decoder(cmd, s):
    """Every word comes from the guest: each read is bounded, each size
    checked against what the call will touch."""
    d = ["static int dec_%s(const uint32_t* nbt_w, size_t nbt_n, size_t* nbt_pos) {" % cmd.name,
         "  size_t nbt_at = *nbt_pos;"]
    if s.scalars:
        d.append("  if (nbt_n - nbt_at < %d) return -1;" % len(s.scalars))
    elif not cmd.params:
        d.append("  (void)nbt_w, (void)nbt_n;")
    for p in s.scalars:
        if p.base in FLOATS:
            d.append("  %s %s;\n  memcpy(&%s, &nbt_w[nbt_at++], 4);" % (p.ctype, p.name, p.name))
        else:
            d.append("  const %s %s = (%s)nbt_w[nbt_at++];" % (p.ctype, p.name, p.ctype))
    for p in s.ins:
        d.append("  uint32_t %s_b;" % p.name)
        d.append("  const void* %s_p = nbtgl_get(nbt_w, nbt_n, &nbt_at, &%s_b);" % (p.name, p.name))
        if s.size[p.name] == "STRING":
            d.append("  if (!%s_p || !%s_b || ((const char*)%s_p)[%s_b - 1]) return -1;" % ((p.name,) * 4))
        else:
            d.append("  if (!%s_p || %s_b < %s) return -1;" % (p.name, p.name, s.size[p.name]))
    for p in s.outs:
        d.append("  if (nbt_at >= nbt_n) return -1;")
        d.append("  const uint32_t %s_n = nbt_w[nbt_at++];" % p.name)
        d.append("  if (%s_n != %s || %s_n > NBTGL_RESULT_SIZE) return -1;" % (p.name, s.size[p.name], p.name))
    if s.sync:
        d.append("  uint8_t* nbt_r = nbtgl_result(4%s);" % "".join(" + NBTGL_PAD(%s_n)" % p.name for p in s.outs))
        d.append("  if (!nbt_r) return -1;")
        if s.outs:
            d.append("  size_t nbt_off = 4;")
        for p in s.outs:
            d.append("  %s %s = (%s)(void*)(nbt_r + nbt_off);" % (p.ctype, p.name, p.ctype))
            d.append("  nbt_off += NBTGL_PAD(%s_n);" % p.name)
        if s.outs:
            d.append("  (void)nbt_off;")
    args = ", ".join("(%s)%s_p" % (p.ctype, p.name) if p.pointer and p.const else p.name for p in cmd.params)
    call = "nbtgl_fn.%s(%s)" % (cmd.name[2:], args)
    if cmd.ret != "void":
        d.append("  const %s nbt_v = %s;" % (cmd.ret, call))
        d.append("  memcpy(nbt_r, &nbt_v, sizeof(nbt_v) < 4 ? sizeof(nbt_v) : 4);")
    else:
        d.append("  %s;" % call)
    if cmd.name in RUNNER_TRACKED:
        d.append("  nbtgl_track_%s(%s);" % (cmd.name, args))
    d.append("  *nbt_pos = nbt_at;\n  return %d;\n}" % (1 if s.sync else 0))
    return "\n".join(d)


def generate(commands):
    ids = [BANNER, "#ifndef NBT_GL_COMMANDS_H", "#define NBT_GL_COMMANDS_H", "",
           "/* Command ids on the wire. The GLES 2.0 set is frozen: an id never changes. */",
           "enum nbtgl_id {"]
    ids += ["  %s = %d," % (ident(c), i) for i, c in enumerate(commands, start=1)]
    ids += ["  NBTGL_ID_END", "};", "", "#endif"]

    enc = [BANNER, "#include <string.h>", "", "#include \"gl_stream_guest.h\"", ""]
    dec = [BANNER, "#include <string.h>", "", "#include \"gl_runner.h\"", ""]
    fns = [BANNER, "#ifndef NBT_GL_FUNCTIONS_H", "#define NBT_GL_FUNCTIONS_H", "",
           "#include <GLES2/gl2.h>", "", "struct nbtgl_functions {"]
    entries, decoders = [], []
    for c in commands:
        fns.append("  %s (GL_APIENTRY *%s)(%s);" % (c.ret, c.name[2:], c.types()))
        if c.name in SPECIAL:
            enc.append("%s nbtgl_special_%s(%s);" % (c.ret, c.name, c.decl()))
            entries.append('  {"%s", (void*)nbtgl_special_%s},' % (c.name, c.name))
            if c.name not in GUEST_ONLY:
                dec.append("int nbtgl_special_%s(const uint32_t* w, size_t n, size_t* pos);" % c.name)
                decoders.append("  [%s] = nbtgl_special_%s," % (ident(c), c.name))
            continue
        s = Shape(c)
        if c.name in GUEST_TRACKED:
            enc.append("void nbtgl_track_%s(%s);" % (c.name, c.decl()))
        if c.name in RUNNER_TRACKED:
            dec.append("void nbtgl_track_%s(%s);" % (c.name, c.decl()))
        enc.append(encoder(c, s))
        dec.append(decoder(c, s))
        entries.append('  {"%s", (void*)enc_%s},' % (c.name, c.name))
        decoders.append("  [%s] = dec_%s," % (ident(c), c.name))
    fns += ["};", "", "#endif"]

    enc += ["", "/* Sorted by name, like the ids. */",
            "const struct nbtgl_entry nbtgl_entries[NBTGL_ID_END - 1] = {"] + entries + ["};"]
    dec += ["", "/* NULL: never sent. */",
            "const nbtgl_decoder nbtgl_decoders[NBTGL_ID_END] = {"] + decoders + ["};", "",
            "struct nbtgl_functions nbtgl_fn;",
            "static const char* const nbtgl_names[NBTGL_ID_END - 1] = {"]
    dec += ['  "%s",' % c.name for c in commands]
    dec += ["};", "",
            "int nbtgl_load(void* (*lookup)(const char* name)) {",
            "  void** slots = (void**)&nbtgl_fn;",
            "  int missing = 0;",
            "  for (int i = 0; i < NBTGL_ID_END - 1; ++i)",
            "    if (!(slots[i] = lookup(nbtgl_names[i]))) ++missing;",
            "  return missing;",
            "}"]
    return {"gl_commands.h": ids, "gl_encode.c": enc, "gl_decode.c": dec, "gl_functions.h": fns}


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__.strip().splitlines()[-1])
    for name, lines in generate(gles2_commands(sys.argv[1])).items():
        with open(os.path.join(sys.argv[2], name), "w") as f:
            f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
